"""Parse every AnalogGenie entry, annotate it, and report what the layout flow can use.

Run inside the iic-osic-tools container with the project venv (it imports glayout):

    cd /foss/designs/glayout-martin
    .venv/bin/python learn/data/ingest.py            # after learn/data/fetch_analoggenie.sh

Reads ``learn/external/AnalogGenie/Dataset``. Each entry gives one item (``ag<id>``,
read from ``<id>_full.cir`` when it exists so composite cells become transistors);
the bandgap and LDO entries also give their error amplifier (``ag<id>_opamp``).

Writes
  learn/data/build/schematics.jsonl   one record per item: schematic, annotation, summary
  learn/data/coverage.json            counts (kept in git; regenerated by this script)
  learn/data/coverage.md              the same as tables

v1 layout scope: MOS only, nfet bodies on ground, at most ``MAX_BLOCKS`` blocks.
Everything else stays in the dataset for netlist-only graphs.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

os.environ.setdefault("GLAYOUT_TABLES", "0")

from glayout.schematic import annotate, read_analoggenie, read_analoggenie_opamp  # noqa: E402
from glayout.schematic.to_circuit import UnsupportedCircuit, check_supported  # noqa: E402

LEARN = Path(__file__).resolve().parents[1]
DATASET = LEARN / "external" / "AnalogGenie" / "Dataset"
BUILD = LEARN / "data" / "build"
MAX_BLOCKS = 12


def layout_scope(sch, ann) -> str:
    """'ok' or why the v1 layout flow cannot draw this circuit."""
    if not sch.devices:
        return "no_devices"
    try:
        check_supported(sch)
    except UnsupportedCircuit as e:
        return e.code
    if any(d.kind.startswith(("composite:", "unknown:")) for d in sch.devices):
        return "non_mos"
    if len(ann.blocks) > MAX_BLOCKS:
        return "too_many_blocks"
    return "ok"


def summarise(sch, ann) -> dict:
    kinds = Counter(d.kind for d in sch.devices)
    return {
        "devices": len(sch.devices),
        "kinds": dict(kinds),
        "nets": len(sch.nets()),
        "ports": len(sch.ports),
        "warnings": len(sch.warnings),
        "problems": sch.check(),
        "mos_only": sch.is_mos_only,
        "blocks": len(ann.blocks),
        "block_kinds": dict(Counter(b.kind for b in ann.blocks)),
        "max_block_devices": max((len(b.devices) for b in ann.blocks), default=0),
        "matched_sets": len(ann.matched),
        "symmetric_pairs": len(ann.matched_pairs(symmetric_only=True)),
        "layout_v1": layout_scope(sch, ann),
    }


def items(dataset: Path):
    for folder in sorted((p for p in dataset.iterdir() if p.name.isdigit()), key=lambda p: int(p.name)):
        yield f"ag{folder.name}", "main", lambda f=folder: read_analoggenie(f, strict=False)
        if (folder / f"Opamp{folder.name}.cir").exists():
            yield f"ag{folder.name}_opamp", "opamp_extract", lambda f=folder: read_analoggenie_opamp(f, strict=False)


def git_head(path: Path) -> str:
    try:
        return subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except Exception:
        return "unknown"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dataset", type=Path, default=DATASET)
    ap.add_argument("--limit", type=int, default=0, help="stop after this many items (0 = all)")
    args = ap.parse_args()
    if not args.dataset.exists():
        sys.exit(f"{args.dataset} not found: run learn/data/fetch_analoggenie.sh first")
    BUILD.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    records, errors = [], []
    with open(BUILD / "schematics.jsonl", "w") as out:
        for n, (key, variant, read) in enumerate(items(args.dataset)):
            if args.limit and n >= args.limit:
                break
            try:
                sch = read()
                ann = annotate(sch)
                summary = summarise(sch, ann)
            except Exception as e:      # recorded, never silently dropped
                errors.append({"key": key, "error": f"{type(e).__name__}: {e}"})
                continue
            rec = {"key": key, "ag_id": sch.provenance["analoggenie_id"], "variant": variant,
                   "category": sch.provenance.get("category"), "schematic": sch.to_json(),
                   "annotation": ann.to_json(), "summary": summary}
            out.write(json.dumps(rec, sort_keys=True) + "\n")
            records.append(rec)
    cov = coverage(records, errors)
    cov["analoggenie_sha"] = git_head(args.dataset.parent)
    cov["seconds"] = round(time.time() - t0, 1)
    (LEARN / "data" / "coverage.json").write_text(json.dumps(cov, indent=1, sort_keys=True) + "\n")
    (LEARN / "data" / "coverage.md").write_text(coverage_md(cov))
    print(coverage_md(cov))


def _warning_kind(w: str) -> str:
    for key, kind in (("repeated instance", "renamed"), ("unknown device type", "unknown_type"),
                      ("cannot parse", "unparsable"), ("cannot expand", "unexpandable"), ("no Port", "no_port_file")):
        if key in w:
            return kind
    return "other"


def coverage(records: list[dict], errors: list[dict]) -> dict:
    by_cat = defaultdict(Counter)
    kinds, scope, warn_kinds, blocks_ok, block_kinds_ok = Counter(), Counter(), Counter(), Counter(), Counter()
    for r in records:
        s = r["summary"]
        cat = r["category"] or "unlisted"
        if r["variant"] == "opamp_extract":
            cat += " (opamp extract)"
        c = by_cat[cat]
        c["items"] += 1
        c["mos_only"] += s["mos_only"]
        c["layout_v1"] += s["layout_v1"] == "ok"
        c["devices"] += s["devices"]
        scope[s["layout_v1"]] += 1
        kinds.update(s["kinds"])
        for w in r["schematic"]["warnings"]:
            warn_kinds[_warning_kind(w)] += 1
        if s["layout_v1"] == "ok":
            blocks_ok[s["blocks"]] += 1
            block_kinds_ok.update(s["block_kinds"])
    return {
        "items": len(records), "errors": errors,
        "by_category": {k: dict(v) for k, v in sorted(by_cat.items())},
        "device_kinds": dict(kinds.most_common()),
        "layout_v1": dict(scope.most_common()),
        "layout_v1_blocks": {str(k): v for k, v in sorted(blocks_ok.items())},
        "layout_v1_block_kinds": dict(block_kinds_ok.most_common()),
        "warnings": dict(warn_kinds.most_common(10)),
        "flattened": sum(1 for r in records if r["schematic"]["provenance"].get("flattened")),
        "renamed": sum(1 for r in records if r["schematic"]["provenance"].get("renamed")),
        "with_problems": sum(1 for r in records if r["summary"]["problems"]),
    }


def coverage_md(cov: dict) -> str:
    lines = ["# AnalogGenie coverage", "",
             f"Generated by `learn/data/ingest.py` from AnalogGenie `{cov.get('analoggenie_sha', '?')[:12]}`; "
             "do not edit by hand.", "",
             f"{cov['items']} items parsed ({len(cov['errors'])} errors); {cov['flattened']} read from a flattened "
             f"`_full.cir`; {cov['renamed']} had repeated instance names renamed; {cov['with_problems']} have "
             "structural warnings (unconnected ports or single-pin nets). Reader warnings: "
             + (", ".join(f"{k} {v}" for k, v in cov["warnings"].items()) or "none") + ".", "",
             "## By category", "", "| category | items | MOS only | v1 layout | devices |", "|---|---:|---:|---:|---:|"]
    tot = Counter()
    for cat, c in cov["by_category"].items():
        lines.append(f"| {cat} | {c['items']} | {c['mos_only']} | {c['layout_v1']} | {c['devices']} |")
        tot.update(c)
    lines.append(f"| **total** | **{tot['items']}** | **{tot['mos_only']}** | **{tot['layout_v1']}** | "
                 f"**{tot['devices']}** |")
    lines += ["", "## v1 layout scope", "", "| outcome | items |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in cov["layout_v1"].items()]
    lines += ["", "Blocks per v1 circuit: " + ", ".join(f"{k}: {v}" for k, v in cov["layout_v1_blocks"].items()),
              "", "Block kinds in v1 circuits: " + ", ".join(f"{k} {v}" for k, v in cov["layout_v1_block_kinds"].items()),
              "", "## Device kinds", "", ", ".join(f"{k} {v}" for k, v in cov["device_kinds"].items()), ""]
    if cov["errors"]:
        lines += ["## Errors", ""] + [f"- {e['key']}: {e['error']}" for e in cov["errors"][:50]] + [""]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
